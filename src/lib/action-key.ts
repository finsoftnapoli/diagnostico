// Chiave stabile di un'azione del report: resta la stessa finché il testo non cambia. Funziona nel browser e sul server.
export function actionKey(text: string): string {
  const s = text.trim().toLowerCase().replace(/\s+/g, " ");
  let h1 = 0xdeadbeef;
  let h2 = 0x41c6ce57;
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    h1 = Math.imul(h1 ^ c, 2654435761);
    h2 = Math.imul(h2 ^ c, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return (h2 >>> 0).toString(16).padStart(8, "0") + (h1 >>> 0).toString(16).padStart(8, "0");
}

export const isActionKey = (k: unknown): k is string => typeof k === "string" && /^[0-9a-f]{16}$/.test(k);
